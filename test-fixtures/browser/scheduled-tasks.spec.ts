import { expect, test } from "@playwright/test";

const taskName = "Daily issue classification and compatibility review";

test("overview hides configuration and history until requested; long task results remain usable", async ({ page }) => {
  await page.goto("/scheduled-tasks.html");
  const panel = page.locator("pi-web-scheduled-tasks-panel");
  await expect(panel.getByRole("heading", { name: "Needs attention", exact: true })).toBeVisible();
  await expect(panel.locator(".history-entry")).toHaveCount(0);
  await expect(panel.getByText("project-with-a-long-registered-id", { exact: false })).toHaveCount(0);
  await expect(panel.getByText("main-workspace", { exact: false })).toHaveCount(0);
  const taskLink = panel.getByRole("button", { name: `View task: ${taskName}`, exact: true });
  await expect(taskLink).toHaveCount(1);
  const row = panel.locator("article").filter({ has: page.getByRole("button", { name: `View task: ${taskName}`, exact: true }) });
  const preview = row.getByText("Reviewed 18 issues.", { exact: false }).filter({ visible: true });
  await expect(preview).toBeVisible();
  const fullReport = row.getByText("Shared notes: docs/compatibility.md", { exact: false });
  await expect(fullReport).not.toBeVisible();
  await expect(row.getByRole("link", { name: "Open conversation" })).toBeVisible();
  const disclosure = row.locator("summary");
  await disclosure.scrollIntoViewIfNeeded();
  const toggle = await disclosure.boundingBox();
  if (!toggle) throw new Error("Missing report toggle");
  const x = toggle.x + toggle.width / 2;
  const y = toggle.y + toggle.height / 2;
  await page.mouse.click(x, y);
  await expect(fullReport).toBeVisible();
  await expect(row.locator(".report-preview")).not.toBeVisible();
  await page.mouse.click(x, y);
  await expect(fullReport).not.toBeVisible();
  await expect(preview).toBeVisible();
  const body = panel.locator(".body");
  expect(await body.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await taskLink.click();
  await expect(panel.locator(".view-title")).toBeFocused();
  const history = panel.locator(".history-entry");
  await expect(history).toHaveCount(1);
  const result = history.locator(".result");
  await expect(result.locator(".summary")).not.toBeVisible();
  await result.locator("summary").focus();
  await page.keyboard.press("Enter");
  await expect(result.locator(".summary")).toBeVisible();
  await expect(result.locator(".summary")).toContainText("Reviewed 18 issues.");
  expect(await body.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await result.locator("summary").click();
  await expect(result.locator(".summary")).not.toBeVisible();
  const technical = history.locator(".technical");
  await expect(technical.getByText("project-with-a-long-registered-id", { exact: false })).not.toBeVisible();
  await technical.locator("summary").click();
  await expect(technical.getByText("project-with-a-long-registered-id", { exact: false })).toBeVisible();
  const currentPrompt = panel.locator(".detail-heading .prompt");
  const savedPrompt = history.locator(".prompt");
  await expect(currentPrompt.locator(".prompt-text")).toHaveCount(0);
  await expect(savedPrompt.locator(".prompt-text")).toHaveCount(0);
  await currentPrompt.locator("summary").focus();
  await page.keyboard.press("Enter");
  await expect(currentPrompt.locator(".prompt-text")).toBeVisible();
  expect(await body.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await savedPrompt.locator("summary").click();
  await expect(savedPrompt.locator(".prompt-text")).toHaveText("Review the issues saved for this run.\nRecord the findings.");
  await expect(savedPrompt.locator(".prompt-text")).toBeVisible();
  await currentPrompt.locator("summary").click();
  await expect(currentPrompt.locator(".prompt-text")).not.toBeVisible();
  const open = history.getByRole("link", { name: "Open conversation", exact: true });
  const href = await open.getAttribute("href");
  if (href === null || href === "") throw new Error("Missing conversation URL");
  const destination = new URL(href);
  expect(destination.pathname).toBe("/scheduled-tasks.html");
  expect(destination.searchParams.get("session")).toBe("review-conversation");
  await open.click();
  await expect(page.locator("body")).toHaveAttribute("data-destination", JSON.stringify({ machineId: "local", projectId: "project-with-a-long-registered-id", workspaceId: "main-workspace", sessionId: "review-conversation", view: "chat" }));
  await open.focus();
  await expect(open).toBeFocused();
  const buttonBox = await open.boundingBox();
  const scrollBox = await body.boundingBox();
  expect(buttonBox).not.toBeNull(); expect(scrollBox).not.toBeNull();
  if (buttonBox && scrollBox) {
    expect(buttonBox.x).toBeGreaterThanOrEqual(scrollBox.x);
    expect(buttonBox.x + buttonBox.width).toBeLessThanOrEqual(scrollBox.x + scrollBox.width);
    expect(buttonBox.y).toBeGreaterThanOrEqual(scrollBox.y);
    expect(buttonBox.y + buttonBox.height).toBeLessThanOrEqual(scrollBox.y + scrollBox.height);
  }
  expect(await body.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await panel.getByRole("button", { name: "Overview", exact: true }).click();
  await expect(taskLink).toBeFocused();
  await panel.getByRole("button", { name: "All history", exact: true }).click();
  await expect(history).toHaveCount(1);
});

test("task filters distinguish projects and workspaces while rows show their names", async ({ page }) => {
  await page.goto("/scheduled-tasks.html");
  const panel = page.locator("pi-web-scheduled-tasks-panel");
  const otherProject = panel.getByRole("button", { name: "View task: Weekly dependency review" });
  const otherWorkspace = panel.getByRole("button", { name: "View task: One-off investigation" });
  const selectedWorkspace = panel.getByRole("button", { name: `View task: ${taskName}` });
  await expect(panel.getByText("Dependency tools / Main", { exact: true })).toBeVisible();
  await expect(panel.getByText("PI WEB / Investigation", { exact: true })).toBeVisible();
  const header = panel.locator("header");
  const filters = header.getByRole("group", { name: "Filter tasks" });
  const tabsBox = await filters.boundingBox();
  const refreshBox = await header.getByRole("button", { name: "Refresh" }).boundingBox();
  if (!tabsBox || !refreshBox) throw new Error("Missing toolbar controls");
  expect(tabsBox.x + tabsBox.width).toBeLessThanOrEqual(refreshBox.x);
  expect(tabsBox.y).toBe(refreshBox.y);
  await filters.getByRole("button", { name: "Current project" }).click();
  await expect(otherProject).toHaveCount(0);
  await expect(otherWorkspace).toBeVisible();
  await filters.getByRole("button", { name: "Current workspace" }).click();
  await expect(otherProject).toHaveCount(0);
  await expect(otherWorkspace).toHaveCount(0);
  await selectedWorkspace.click();
  await expect(panel.locator(".detail-heading").getByText("PI WEB / Main", { exact: true })).toBeVisible();
  await panel.getByRole("button", { name: "Overview" }).click();
  await expect(selectedWorkspace).toBeFocused();
  await expect(otherWorkspace).toHaveCount(0);
  await filters.getByRole("button", { name: "All tasks" }).click();
  await expect(otherProject).toBeVisible();
  expect(await panel.locator(".body").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
});

test("paused and archived tasks remain discoverable and controls work in narrow RTL layouts", async ({ page }) => {
  await page.goto("/scheduled-tasks.html");
  const panel = page.locator("pi-web-scheduled-tasks-panel");
  await expect(panel.locator(".task").first()).toBeVisible();
  const archived = panel.getByRole("button", { name: /Archived compatibility check/ });
  await expect(archived).not.toBeVisible();
  await panel.locator(".archived-tasks > summary").click();
  await expect(archived).toBeVisible();
  await page.getByRole("button", { name: "RTL", exact: true }).click();
  await expect(panel.locator(".panel")).toHaveAttribute("dir", "rtl");
  expect(await panel.locator(".body").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await archived.click();
  await expect(panel.locator(".view-title")).toBeFocused();
  const refresh = panel.locator("header button");
  await refresh.click(); await expect(refresh).toBeEnabled();
  await panel.locator(".back").click();
  await expect(archived).toBeFocused();
});
